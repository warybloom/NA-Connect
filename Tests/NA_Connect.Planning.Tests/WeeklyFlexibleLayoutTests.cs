    [Fact]
    public void NewEnglishOnlyModelIsRecognizedAndMapsToSameInternalFields()
    {
        using var p = Empty();
        var s = p.Workbook.Worksheets.Add("New Model");
        for (int c = 0; c < 21; c++)
        {
            var f = WeeklyScheduleContract.Fields[c];
            s.Cells[7,c+1].Value = NovosCabecalhosIngles.TryGetValue(f.Header, out var alias) ? alias : f.Header;
            s.Cells[8,c+1].Value = f.Type == typeof(DateTime) ? new DateTime(2026,8,12) : f.Type == typeof(decimal) ? 15.25m : f.Percentage ? "50%" : "valor " + c;
        }
        var header = WeeklyScheduleContract.Inspect(s);
        Assert.True(header.Valid);
        Assert.Equal(21,header.Map.Count);
        Assert.Empty(header.Missing);
        var r = Assert.Single(WeeklyScheduleContract.Read(p,"project",fileName:"weekly-new-model.xlsx").AsEnumerable());
        Assert.Equal("OK",r["Status_Importacao"]);
        Assert.All(WeeklyScheduleContract.Fields,f => Assert.NotEqual(DBNull.Value,r[f.SqlColumn]));
    }

