    private static ExcelWorksheet Sheet(ExcelPackage p, int count = 21, string name = "Qualquer nome", int header = 7)
    {
        var s = p.Workbook.Worksheets.Add(name);
        for (int c = 0; c < count; c++)
        {
            var f = WeeklyScheduleContract.Fields[c];
            s.Cells[header,c+1].Value = f.Header;
            s.Cells[header+1,c+1].Value = f.Type == typeof(DateTime) ? new DateTime(2026,8,12) : f.Type == typeof(decimal) ? 15.25m : f.Percentage ? "50%" : "valor " + c;
        }
        return s;
    }
    private sealed class CaptureLog : ILogger
