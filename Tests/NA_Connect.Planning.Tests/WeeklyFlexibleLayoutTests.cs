    [Fact]
    public void ReadOnlyRealSchemaEvidenceMatchesEveryBulkColumnIncludingIdentityAndScale()
    {
        var json=File.ReadAllText(Path.Combine(AppContext.BaseDirectory,"Fixtures","OfficialPlanning","sql-schema-tolerant-20260911.json"));
        using var evidence=System.Text.Json.JsonDocument.Parse(json);
        var columns=evidence.RootElement.EnumerateArray().Where(c=>c.GetProperty("TABLE_NAME").GetString()==WeeklyScheduleContract.Table).ToArray();
        Assert.Equal(30,columns.Length);
        var schema=columns.ToDictionary(c=>c.GetProperty("COLUMN_NAME").GetString()!,c=>c.GetProperty("DATA_TYPE").GetString()!);
        var table=WeeklyScheduleContract.CreateTable();WeeklyScheduleContract.PrepareForSql(table,schema);
        Assert.Equal(1,columns.Single(c=>c.GetProperty("COLUMN_NAME").GetString()=="Id_Registro").GetProperty("IS_IDENTITY").GetInt32());
        foreach(var c in columns.Where(c=>c.GetProperty("COLUMN_NAME").GetString()!="Id_Registro"))Assert.Equal("YES",c.GetProperty("IS_NULLABLE").GetString());
        foreach(var c in columns.Where(c=>c.GetProperty("DATA_TYPE").GetString()=="decimal"))
        { Assert.Equal(18,c.GetProperty("NUMERIC_PRECISION").GetInt32());Assert.Equal(6,c.GetProperty("NUMERIC_SCALE").GetInt32()); }
        foreach(string other in new[]{"tb_ExternalActionLog","tb_InternalActionLog","tb_ScopeDeviation","tb_HoldControl"})
            Assert.DoesNotContain(evidence.RootElement.EnumerateArray(),c=>c.GetProperty("TABLE_NAME").GetString()==other && c.GetProperty("COLUMN_NAME").GetString()=="Diagnostico_Importacao");
    }

